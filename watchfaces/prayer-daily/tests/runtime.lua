local directory = arg[1]
package.path = directory .. '/?.lua;' .. package.path
local calendar = require('prayer_calendar')
local prayers = require('prayer_logic')
local vectors = dofile(directory .. '/vectors.lua')
for _, vector in ipairs(vectors) do
    local state = prayers.state(calendar, vector.at)
    assert(state.status == vector.status, 'Status at ' .. vector.at)
    assert(state.phase == vector.phase, 'Phase at ' .. vector.at)
    assert(state.countdown == vector.countdown, 'Countdown at ' .. vector.at)
    assert((state.next and state.next.id) == vector.next, 'Prayer at ' .. vector.at)
    assert((state.tomorrow or false) == vector.tomorrow, 'Tomorrow at ' .. vector.at)
    assert(state.source == vector.source, 'Iqama source at ' .. vector.at)
    assert((state.adhanNow or false) == vector.adhanNow, 'Adhan transition at ' .. vector.at)
end
assert(prayers.countdown(90000) == '25:00:00')
assert(prayers.countdown(-1) == '00:00:00')
assert(prayers.state({ days = {} }, 0).status == 'unavailable')
local gap = { days = { calendar.days[1], calendar.days[3] } }
assert(prayers.state(gap, calendar.days[1].prayers[5].iqamaAt + 60).status == 'missing-next-day')
print(#vectors .. ' Lua/JS boundary comparisons passed (including DST).')

local host = dofile((arg[0]:match('(.*/)') or './') .. 'host.lua')
local target = calendar.days[1].prayers[2].at
local app = host.start(directory, target - 120)
assert(app:text(210) == '00:02:00')
assert(app:text(185) == 'Dhuhr in')
assert(app:text(64) == '12:56')
assert(app:text(127) == 'FR 16.10.2026')
assert(app:text(315, 14) == '--°C')
assert(app:text(315, 114) == '--%')
assert(app:text(411, 14) == '--')
assert(app:text(411, 114) == '--')
app:metric('systemStatusBattery', 90)
app:metric('weatherCurrentTemperature', 10)
app:metric('weatherCurrentWeather', 1)
app:metric('healthStepCount', 3024)
app:metric('healthHeartRate', 72)
assert(app:text(315, 114) == '90%')
assert(app:text(315, 14) == '10°C')
assert(app:text(349) == 'Wolkig')
assert(app:text(411, 14) == '3.024')
assert(app:text(411, 114) == '72')
app:tick(target - 119)
assert(app:text(210) == '00:01:59', 'Must update on timeSecond')
app:tick(target - 118)
assert(app:text(210) == '00:01:58')
ScreenStateChangedCB('ON', 'OFF', '')
local writes = app.writes
app:tick(target - 50)
app:metric('healthStepCount', 3100)
app:metric('healthHeartRate', 80)
assert(app.writes == writes, 'No repaint while screen off, including metric callbacks')
assert(app:text(210) == '00:01:58')
ScreenStateChangedCB('OFF', 'ON', '')
assert(app:text(210) == '00:00:50', 'Must recompute immediately on wake')
assert(app:text(411, 14) == '3.100', 'Metric changes must appear on wake')
assert(app:text(411, 114) == '80')
app:tick(target)
assert(app:text(185) == 'Iqama in', 'Adhan must switch the caption to Iqama')
assert(app:text(210) == '00:10:00')
app:tick(target + 60)
assert(app:text(210) == '00:09:00')
app:tick(calendar.days[1].prayers[2].iqamaAt)
assert(app:text(185) == 'Iqama jetzt')
assert(app:text(210) == '00:00:00')
app:tick(calendar.days[1].prayers[2].iqamaAt + 60)
assert(app:text(210) == prayers.state(calendar, app.now).countdown)
app:tick(target - 1)
assert(app:text(210) == '00:00:01', 'Backward clock correction must recompute')
local fajr = calendar.days[1].prayers[1]
app:tick(fajr.at - 1)
assert(app:text(185) == 'Fajir in')
assert(app:text(210) == '00:00:01')
app:tick(fajr.at)
assert(app:text(185) == 'Iqama in')
assert(app:text(210) == '00:10:00')
app:tick(fajr.iqamaAt)
assert(app:text(210) == '00:00:00')
app:tick(fajr.iqamaAt + 60)
assert(app:text(185) == 'Shuruk in')
assert(app:text(210) == prayers.countdown(calendar.days[1].sunriseAt - app.now))
app:tick(calendar.days[1].sunriseAt)
assert(app:text(185) == 'Shuruk jetzt')
assert(app:text(210) == '00:00:00')
app:tick(calendar.days[1].sunriseAt + 60)
assert(app:text(185) == 'Dhuhr in')
assert(app:text(210) == prayers.countdown(target - app.now))
pageOnPause()
app:tick(calendar.days[1].prayers[5].iqamaAt + 60)
pageOnResume()
assert(app:text(185) == 'Fajir in', 'Tomorrow must use the next prayer name')
assert(app:text(210) == prayers.countdown(calendar.days[2].prayers[1].at - app.now))
app:tick(calendar.days[#calendar.days].finish)
assert(app:text(210) == '--:--:--')
assert(app:text(185) == 'Kalender erneuern')

local captions = { 'Fajir in', 'Dhuhr in', 'Asr in', 'Maghrib in', 'Isha in' }
for index, prayer in ipairs(calendar.days[1].prayers) do
    app:tick(prayer.at - 1)
    assert(app:text(185) == captions[index], 'Caption for ' .. prayer.id)
    app:tick(prayer.at)
    assert(app:text(185) == 'Iqama in', 'Iqama caption for ' .. prayer.id)
end

app:metric('weatherCurrentTemperature', -12)
app:metric('healthStepCount', 0)
app:metric('systemStatusBattery', 0)
assert(app:text(315, 14) == '-12°C')
assert(app:text(411, 14) == '0', 'Midnight step reset is a valid reading')
assert(app:text(315, 114) == '0%', 'Empty battery is a valid reading')
app:metric('healthStepCount', 99999)
assert(app:text(411, 14) == '99.999')
for _, raw in ipairs({ 0, -256, 32767 * 256, math.huge, 0/0, 'invalid' }) do
    app:publish('healthHeartRate', raw)
    assert(app:text(411, 114) == '--', 'Unavailable pulse must not become a valid measurement')
end
app:metric('systemStatusBattery', 101)
app:metric('weatherCurrentTemperature', 32767)
app:metric('healthStepCount', -1)
app:metric('weatherCurrentWeather', 99)
assert(app:text(315, 114) == '--%')
assert(app:text(315, 14) == '--°C')
assert(app:text(411, 14) == '--')
assert(app:text(349) == '--', 'Unknown weather must not be guessed')
app:metric('weatherCurrentWeather', 301)
assert(app:text(349) == 'Regen')
for _, obj in ipairs(app.labels) do assert(obj.flags[2], 'Long-press must bubble to system') end
for _, obj in ipairs(app.labels) do
    local p = obj.props
    assert(p.align == nil, 'Text labels must not use dynamic object alignment')
    assert(p.x >= 0 and p.w > 0 and p.x + p.w <= 212 and p.h >= p.text_font.size, 'Text must have a fixed display lane')
    assert(p.y >= 0 and p.y + p.h <= 520, 'Text lane outside screen')
end
local unsupported = { systemStatusBattery = true, weatherCurrentTemperature = true,
    weatherCurrentWeather = true, healthStepCount = true, healthHeartRate = true }
local fallback = host.start(directory, target - 120, unsupported)
fallback:tick(target - 119)
assert(fallback:text(210) == '00:01:59', 'Optional metrics must not break countdown')
print('Lifecycle and live countdown passed: Adhan, Iqama, sunrise, sleep/wake, clock correction, tomorrow, expiry.')
print('Band metrics passed: Q24.8, invalid readings, midnight reset, sleep/wake and unsupported channels.')
